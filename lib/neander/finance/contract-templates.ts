/** 「(주)네안데르」 → 「주식회사 네안데르」. 계약서에는 줄이지 않은 상호를 쓴다 */
export const formalName = (name: string) => name.trim().replace(/^\(주\)\s*/, "주식회사 ").replace(/\s*\(주\)$/, " 주식회사");

/**
 * 양식 하나를 프로젝트 값으로 채워 본문을 짓는다.
 *
 * 지은 뒤로는 그냥 글이다 — 양식과 이어져 있지 않다. 양식을 고쳐도 이미
 * 만든 계약서는 바뀌지 않는다(체결한 계약서의 글이 저절로 바뀌면 안 된다).
 */
export function buildContractBody(id: ContractTemplateId, seed: ContractSeed): ContractBody {
  const meta = contractTemplate(id);
  const them: ContractParty = { ...emptyParty(), name: seed.client.trim() };
  const us: ContractParty = { ...seed.our, name: formalName(seed.our.name) };
  const name = seed.projectName.trim();
  const bank = seed.bank?.trim() ?? "";

  let clauses: ContractClause[];
  let terms: ContractTerm[];
  let items: ContractItem[] = [];
  const lines = seed.quoteLines.filter((l) => l.name.trim()).map((l) => ({ ...l, id: rid() }));

  switch (id) {
    case "supply":
      clauses = supplyClauses(seed);
      terms = [term("납품기한"), term("납품 장소"), term("입금 계좌", bank)];
      items = lines.length > 0 ? lines : [{ id: rid(), name: "", qty: 1, unitPrice: 0 }];
      break;
    case "outsource":
      clauses = outsourceClauses(seed);
      // 납품받는 곳은 대개 우리 사무실이다. 입금 계좌는 상대 것이라 비워 둔다
      terms = [term("납품기한"), term("납품 장소", us.address), term("입금 계좌")];
      items = [{ id: rid(), name: "", qty: 1, unitPrice: 0 }];
      break;
    case "collab":
      clauses = collabClauses();
      terms = [
        term("협업 상품"),
        term("판매 채널"),
        term("로열티율", `순매출액의 ${BLANK}%`),
        term("정산 주기", "분기별 — 분기가 끝난 다음 달 말일까지 정산서를 보낸다"),
      ];
      break;
    default: {
      clauses = serviceClauses(seed);
      const from = longDate(seed.eventStart);
      const to = longDate(seed.eventEnd);
      const event = from && to && from !== to ? `${from} ~ ${to}` : from || to;
      terms = [term("행사 기간", event), term("행사 장소"), term("입금 계좌", bank)];
    }
  }

  return {
    template: id,
    ourSide: meta.ourSide,
    roleA: meta.roleA,
    roleB: meta.roleB,
    partyA: meta.ourSide === "a" ? us : them,
    partyB: meta.ourSide === "a" ? them : us,
    heading: [name, meta.kind, "계약서"].filter(Boolean).join(" "),
    preamble: `“갑”과 “을”은 아래 「계약의 개요」에 적은 ${meta.kind} 계약(이하 “본 계약”이라 한다)을 다음과 같이 체결한다.`,
    terms,
    items,
    clauses,
    closing: CLOSING,
    ...(seed.sealId ? { sealId: seed.sealId } : {}),
  };
}
