/** 양식이 프로젝트에서 받아 오는 것 */
export interface ContractSeed {
  /** 프로젝트 이름 — 제목과 계약명의 출발점 */
  projectName: string;
  /** 발주처 · 주최 */
  client: string;
  amount: number;
  vatMode: VatMode;
  startDate?: string;
  endDate?: string;
  /** 행사가 열리는 날 — 용역 계약의 「행사 기간」 행이 된다 */
  eventStart?: string;
  eventEnd?: string;
  /** 프로젝트의 입금 일정 (선금·중도금·잔금) — 우리가 받는 계약의 지급 조항이 된다 */
  installments: { kind: string; amount: number; dueDate?: string }[];
  /** 프로젝트의 최근 견적서 품목 — 용역 범위 · 공급 품목의 출발점 */
  quoteLines: ContractItem[];
  /** 우리 쪽 서명란 */
  our: ContractParty;
  sealId?: string;
  /** 지난 계약서에 적었던 입금 계좌 */
  bank?: string;
}

const rid = () => Math.random().toString(36).slice(2, 10);

/** 「2026년 9월 3일」 */
export function longDate(ymd?: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(ymd ?? "");
  return m ? `${m[1]}년 ${Number(m[2])}월 ${Number(m[3])}일` : "";
}

const won = (n: number) => Math.round(n).toLocaleString("ko-KR");
const clause = (title: string, ...lines: string[]): ContractClause => ({ id: rid(), title, text: lines.join("\n") });
const term = (label: string, value = ""): ContractTerm => ({ id: rid(), label, value });

