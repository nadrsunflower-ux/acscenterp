/**
 * 대금을 나눠 받는 줄. 프로젝트에 입금 일정이 있으면 그 금액과 날짜를 그대로
 * 적고, 없으면 선금 50% · 잔금 50% 로 시작한다 — 검수 뒤 전액(JIMFF)은
 * 우리가 재료비를 먼저 다 대는 구조였다.
 */
function paymentLines(seed: ContractSeed, settle: string, useSchedule: boolean): string[] {
  const rows = useSchedule ? seed.installments.filter((i) => i.amount > 0) : [];
  if (rows.length > 0) {
    return rows.map(
      (i, k) => `  ${k + 1}. ${i.kind}: 금 ${won(i.amount)}원${i.dueDate ? ` — ${longDate(i.dueDate)}까지` : ""}`,
    );
  }
  return [
    "  1. 선금: 계약금액의 50% — 계약 체결일로부터 7일 이내",
    `  2. 잔금: 계약금액의 50% — ${settle}로부터 14일 이내`,
  ];
}

